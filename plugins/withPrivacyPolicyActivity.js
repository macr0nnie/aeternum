// =============================================================================
// Aeternum — Health Connect privacy-policy activity config plugin
// =============================================================================
// WHY THIS EXISTS
// Health Connect links to an app's privacy policy from its permission screen
// (ACTION_SHOW_PERMISSIONS_RATIONALE, and on Android 14+ the
// VIEW_PERMISSION_USAGE alias). Google requires that link to show the policy;
// pointing it at MainActivity just opens the game. This plugin generates a tiny
// activity that opens `expo.extra.privacyPolicyUrl` in the browser and closes,
// and moves both entry points onto it.
//
// Must be listed FIRST in app.json plugins: manifest mods run in reverse list
// order, so listing it first makes it run last — after react-native-health-connect
// and withHealthConnectLaunchMode have added the filter and alias. Idempotent.
// =============================================================================

const fs = require('fs')
const path = require('path')
const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins')

const RATIONALE_ACTION = 'androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE'
const ACTIVITY = '.PrivacyPolicyActivity'

function kotlinSource(pkg, url) {
  return `package ${pkg}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

// Generated by plugins/withPrivacyPolicyActivity.js — do not edit.
class PrivacyPolicyActivity : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    try {
      startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(${JSON.stringify(url)})))
    } catch (e: Exception) {
      // No browser installed — nothing else we can show.
    }
    finish()
  }
}
`
}

function isRationale(filter) {
  return (filter['action'] ?? []).some((a) => a['$']?.['android:name'] === RATIONALE_ACTION)
}

module.exports = function withPrivacyPolicyActivity(config) {
  const url = config.extra?.privacyPolicyUrl
  const pkg = config.android?.package
  if (!url || !pkg) {
    throw new Error(
      '[withPrivacyPolicyActivity] expo.extra.privacyPolicyUrl and expo.android.package ' +
        'must be set — Health Connect needs a privacy policy to link to.',
    )
  }

  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults['manifest']['application'][0]

    // Take the rationale filter off MainActivity…
    for (const activity of app['activity'] ?? []) {
      if (Array.isArray(activity['intent-filter'])) {
        activity['intent-filter'] = activity['intent-filter'].filter((f) => !isRationale(f))
      }
    }

    // …and give it to the privacy-policy activity.
    if (!app['activity'].some((a) => a['$']?.['android:name'] === ACTIVITY)) {
      app['activity'].push({
        $: {
          'android:name': ACTIVITY,
          'android:exported': 'true',
          'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
        },
        'intent-filter': [{ action: [{ $: { 'android:name': RATIONALE_ACTION } }] }],
      })
    }

    // Android 14+ permission-usage alias → same activity.
    for (const alias of app['activity-alias'] ?? []) {
      if (alias['$']?.['android:name'] === 'ViewPermissionUsageActivity') {
        alias['$']['android:targetActivity'] = ACTIVITY
      }
    }
    return cfg
  })

  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...pkg.split('.'),
      )
      fs.mkdirSync(dir, { recursive: true })
      fs.writeFileSync(path.join(dir, 'PrivacyPolicyActivity.kt'), kotlinSource(pkg, url))
      return cfg
    },
  ])
}
